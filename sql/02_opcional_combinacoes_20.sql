-- Tabela OPCIONAL para o gerador de combinacoes de 20 dezenas.
-- Nao e necessaria para o dashboard principal.
-- Popule com: python gerador_combinacoes_20.py
-- ============================================================================

USE LOTOFACIL;
GO

IF OBJECT_ID('dbo.COMBINACOES_LOTOFACIL20', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.COMBINACOES_LOTOFACIL20 (
        ID INT IDENTITY(1,1) PRIMARY KEY,
        N1  TINYINT NOT NULL CHECK (N1  BETWEEN 1 AND 25),
        N2  TINYINT NOT NULL CHECK (N2  BETWEEN 1 AND 25),
        N3  TINYINT NOT NULL CHECK (N3  BETWEEN 1 AND 25),
        N4  TINYINT NOT NULL CHECK (N4  BETWEEN 1 AND 25),
        N5  TINYINT NOT NULL CHECK (N5  BETWEEN 1 AND 25),
        N6  TINYINT NOT NULL CHECK (N6  BETWEEN 1 AND 25),
        N7  TINYINT NOT NULL CHECK (N7  BETWEEN 1 AND 25),
        N8  TINYINT NOT NULL CHECK (N8  BETWEEN 1 AND 25),
        N9  TINYINT NOT NULL CHECK (N9  BETWEEN 1 AND 25),
        N10 TINYINT NOT NULL CHECK (N10 BETWEEN 1 AND 25),
        N11 TINYINT NOT NULL CHECK (N11 BETWEEN 1 AND 25),
        N12 TINYINT NOT NULL CHECK (N12 BETWEEN 1 AND 25),
        N13 TINYINT NOT NULL CHECK (N13 BETWEEN 1 AND 25),
        N14 TINYINT NOT NULL CHECK (N14 BETWEEN 1 AND 25),
        N15 TINYINT NOT NULL CHECK (N15 BETWEEN 1 AND 25),
        N16 TINYINT NOT NULL CHECK (N16 BETWEEN 1 AND 25),
        N17 TINYINT NOT NULL CHECK (N17 BETWEEN 1 AND 25),
        N18 TINYINT NOT NULL CHECK (N18 BETWEEN 1 AND 25),
        N19 TINYINT NOT NULL CHECK (N19 BETWEEN 1 AND 25),
        N20 TINYINT NOT NULL CHECK (N20 BETWEEN 1 AND 25),
        QtdeRepetidos TINYINT NULL,
        RepetidosMesmaPosicao TINYINT NULL,
        DataGeracao DATETIME2 DEFAULT GETDATE(),
        Processado BIT DEFAULT 0,
        CONSTRAINT CK_COMB20_ORDENADO CHECK (
            N1 < N2  AND N2 < N3  AND N3 < N4  AND N4 < N5  AND
            N5 < N6  AND N6 < N7  AND N7 < N8  AND N8 < N9  AND N9 < N10 AND
            N10 < N11 AND N11 < N12 AND N12 < N13 AND N13 < N14 AND N14 < N15 AND
            N15 < N16 AND N16 < N17 AND N17 < N18 AND N18 < N19 AND N19 < N20
        )
    );
    PRINT 'Tabela COMBINACOES_LOTOFACIL20 criada.';
END
ELSE PRINT 'Tabela COMBINACOES_LOTOFACIL20 ja existe.';
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_COMBINACOES_20_Processado' AND object_id = OBJECT_ID('dbo.COMBINACOES_LOTOFACIL20'))
    CREATE INDEX IX_COMBINACOES_20_Processado ON dbo.COMBINACOES_LOTOFACIL20(Processado);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_COMBINACOES_20_QtdeRepetidos' AND object_id = OBJECT_ID('dbo.COMBINACOES_LOTOFACIL20'))
    CREATE INDEX IX_COMBINACOES_20_QtdeRepetidos ON dbo.COMBINACOES_LOTOFACIL20(QtdeRepetidos);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_COMBINACOES_20_DataGeracao' AND object_id = OBJECT_ID('dbo.COMBINACOES_LOTOFACIL20'))
    CREATE INDEX IX_COMBINACOES_20_DataGeracao ON dbo.COMBINACOES_LOTOFACIL20(DataGeracao);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_COMBINACOES_20_Numeros' AND object_id = OBJECT_ID('dbo.COMBINACOES_LOTOFACIL20'))
    CREATE INDEX IX_COMBINACOES_20_Numeros ON dbo.COMBINACOES_LOTOFACIL20(N1, N2, N3, N4, N5);
GO

PRINT '02_opcional_combinacoes_20.sql concluido.';
GO
